export class Canvas {
  constructor(w,h,bg=[255,255,255]){ this.w=w; this.h=h; this.d=new Uint8Array(w*h*3);
    for(let i=0;i<w*h;i++){ this.d[i*3]=bg[0]; this.d[i*3+1]=bg[1]; this.d[i*3+2]=bg[2]; } }
  px(x,y,c){ x=Math.round(x); y=Math.round(y);
    if(x<0||y<0||x>=this.w||y>=this.h) return;
    const o=(y*this.w+x)*3; this.d[o]=c[0]; this.d[o+1]=c[1]; this.d[o+2]=c[2]; }
  rect(x,y,w,h,c){ for(let j=0;j<h;j++) for(let i=0;i<w;i++) this.px(x+i,y+j,c); }
  frame(x,y,w,h,c){ for(let i=0;i<w;i++){ this.px(x+i,y,c); this.px(x+i,y+h-1,c);} 
    for(let j=0;j<h;j++){ this.px(x,y+j,c); this.px(x+w-1,y+j,c);} }
  line(x0,y0,x1,y1,c,lw=1){ x0=Math.round(x0);y0=Math.round(y0);x1=Math.round(x1);y1=Math.round(y1);
    const dx=Math.abs(x1-x0), dy=Math.abs(y1-y0), sx=x0<x1?1:-1, sy=y0<y1?1:-1;
    let err=dx-dy, x=x0, y=y0, guard=0;
    while(guard++<100000){ this.dot(x,y,c,lw); if(x===x1&&y===y1) break; const e2=2*err;
      if(e2>-dy){ err-=dy; x+=sx; } if(e2<dx){ err+=dx; y+=sy; } } }
  dot(x,y,c,lw=1){ if(lw<=1){ this.px(x,y,c); return; }
    const a=Math.floor(lw/2); for(let j=-a;j<=a;j++) for(let i=-a;i<=a;i++) this.px(x+i,y+j,c); }
  circle(x,y,r,c){ for(let a=0;a<360;a+=4){ this.px(x+r*Math.cos(a*Math.PI/180), y+r*Math.sin(a*Math.PI/180), c); } }
  fillCircle(x,y,r,c){ for(let j=-r;j<=r;j++) for(let i=-r;i<=r;i++) if(i*i+j*j<=r*r) this.px(x+i,y+j,c); }
  text(x,y,s,c,scale=1){ let cx=x;
    for(const ch of String(s).toUpperCase()){ const g=F[ch]||F["?"];
      for(let r=0;r<7;r++) for(let k=0;k<5;k++) if(g[r][k]==="#"){ 
        if(scale===1) this.px(cx+k,y+r,c); else this.rect(cx+k*scale,y+r*scale,scale,scale,c); }
      cx += 6*scale; } }
  textW(s,scale=1){ return String(s).length*6*scale; }
  textCenter(x,y,s,c,scale=1){ this.text(x-this.textW(s,scale)/2, y, s, c, scale); }
  textRight(x,y,s,c,scale=1){ this.text(x-this.textW(s,scale), y, s, c, scale); }
  save(path){ fs.writeFileSync(path, encodePNG(this.w,this.h,this.d)); }
}

function crc32(buf){ let c, crc=0xffffffff;
  for(let n=0;n<buf.length;n++){ c=(crc^buf[n])&0xff; for(let k=0;k<8;k++) c = c&1 ? 0xedb88320^(c>>>1) : c>>>1; crc=(crc>>>8)^c; }
  return (crc^0xffffffff)>>>0; }
function chunk(type,data){ const len=Buffer.alloc(4); len.writeUInt32BE(data.length,0);
  const t=Buffer.from(type,"ascii"); const body=Buffer.concat([t,data]);
  const crc=Buffer.alloc(4); crc.writeUInt32BE(crc32(body),0);
  return Buffer.concat([len,body,crc]); }
export function encodePNG(w,h,rgb){
  const sig=Buffer.from([137,80,78,71,13,10,26,10]);
  const ihdr=Buffer.alloc(13); ihdr.writeUInt32BE(w,0); ihdr.writeUInt32BE(h,4);
  ihdr[8]=8; ihdr[9]=2; ihdr[10]=0; ihdr[11]=0; ihdr[12]=0;
  const raw=Buffer.alloc(h*(w*3+1));
  for(let y=0;y<h;y++){ raw[y*(w*3+1)]=0; rgb.subarray(y*w*3,(y+1)*w*3).forEach((v,i)=>{ raw[y*(w*3+1)+1+i]=v; }); }
  const idat=zlib.deflateSync(raw,{level:9});
  return Buffer.concat([sig, chunk("IHDR",ihdr), chunk("IDAT",idat), chunk("IEND",Buffer.alloc(0))]);
}

// ---------- axis helper ----------
export function niceTicks(lo,hi,n=5){
  const span=hi-lo; if(span<=0) return [lo];
  const raw=span/n; const mag=Math.pow(10,Math.floor(Math.log10(raw)));
  const norm=raw/mag; let step;
  if(norm<=1) step=1; else if(norm<=2) step=2; else if(norm<=2.5) step=2.5; else if(norm<=5) step=5; else step=10;
  step*=mag;
  const start=Math.ceil(lo/step)*step; const out=[];
  for(let v=start; v<=hi+1e-9; v+=step) out.push(Math.abs(v)<step*1e-9?0:v);
  return out;
}
